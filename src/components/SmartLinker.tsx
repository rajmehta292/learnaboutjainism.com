import React from 'react';
import fs from 'fs';
import path from 'path';
import { Link } from '@/i18n/routing';

// Cache the ontology map in memory on the server so we only build it once
let ontologyMap: { title: string; id: string }[] | null = null;

function getOntologyMap() {
  if (ontologyMap) return ontologyMap;
  
  try {
    const filePath = path.join(process.cwd(), 'src', 'data', 'ontology.json');
    const fileContents = fs.readFileSync(filePath, 'utf8');
    const ontology = JSON.parse(fileContents);
    
    const map: { title: string; id: string }[] = [];
    
    for (const domain of ontology.domains) {
      for (const topic of domain.topics) {
        map.push({ title: topic.title, id: topic.topic_id });
      }
    }
    
    // Sort by length descending so longer terms match first (e.g., "Kevala Jnana" before "Jnana")
    map.sort((a, b) => b.title.length - a.title.length);
    ontologyMap = map;
    return map;
  } catch (error) {
    console.error("Failed to load ontology for SmartLinker", error);
    return [];
  }
}

export default function SmartLinker({ text }: { text: string }) {
  if (!text) return <>{text}</>;
  
  const map = getOntologyMap();
  if (map.length === 0) return <>{text}</>;

  // Build the regex
  const escapedTerms = map.map(t => t.title.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'));
  const regex = new RegExp(`\\b(${escapedTerms.join('|')})\\b`, 'gi');

  const parts = text.split(regex);

  const parsedText = parts.map((part, i) => {
    // If it's an odd index, it's a match (due to capturing group in regex)
    if (i % 2 !== 0) {
      const matchedTerm = map.find(t => t.title.toLowerCase() === part.toLowerCase());
      if (matchedTerm) {
        
        // Try to read the topic JSON to get the overview for the tooltip
        let overview = "Content for this topic is currently being generated by the AI research pipeline.";
        try {
          const topicPath = path.join(process.cwd(), 'src', 'data', 'topics', `${matchedTerm.id}.json`);
          if (fs.existsSync(topicPath)) {
            const topicData = JSON.parse(fs.readFileSync(topicPath, 'utf8'));
            if (topicData.overview) {
              // Truncate overview if it's too long
              overview = topicData.overview.length > 200 
                ? topicData.overview.substring(0, 200) + '...' 
                : topicData.overview;
            }
          }
        } catch (e) {
          // Silent catch, fallback to default text
        }

        return (
          <span key={i} className="group relative inline-block">
            <Link 
              href={`/ontology/${matchedTerm.id}`}
              className="text-aged-brass border-b border-aged-brass/30 hover:border-aged-brass transition-colors"
            >
              {part}
            </Link>
            
            {/* Tooltip */}
            <span className="pointer-events-none absolute bottom-full left-1/2 -translate-x-1/2 mb-2 w-64 opacity-0 transition-opacity group-hover:opacity-100 z-50">
              <span className="block bg-[#1A252C] text-[#FAF9F6] text-xs leading-relaxed p-3 rounded shadow-lg font-sans border border-carved-line/20">
                <strong className="block text-aged-brass mb-1">{matchedTerm.title}</strong>
                {overview}
              </span>
              {/* Tooltip arrow */}
              <span className="absolute top-full left-1/2 -translate-x-1/2 border-4 border-transparent border-t-[#1A252C]"></span>
            </span>
          </span>
        );
      }
    }
    // Return standard text for non-matches
    return <React.Fragment key={i}>{part}</React.Fragment>;
  });

  return <>{parsedText}</>;
}
