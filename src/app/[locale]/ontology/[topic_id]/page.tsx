import React from 'react';
import fs from 'fs';
import path from 'path';
import { notFound } from 'next/navigation';
import ScriptureReader from '@/components/ScriptureReader';

export default async function TopicPage({ params }: { params: Promise<{ topic_id: string }> }) {
  const { topic_id } = await params;
  
  // First, find the title of the topic from the ontology.json
  const ontologyPath = path.join(process.cwd(), 'src', 'data', 'ontology.json');
  let title = "Unknown Topic";
  if (fs.existsSync(ontologyPath)) {
    const ontology = JSON.parse(fs.readFileSync(ontologyPath, 'utf8'));
    for (const domain of ontology.domains) {
      const found = domain.topics.find((t: any) => t.topic_id === topic_id);
      if (found) {
        title = found.title;
        break;
      }
    }
  }

  // Then, read the specific topic JSON file
  const filePath = path.join(process.cwd(), 'src', 'data', 'topics', `${topic_id}.json`);
  
  if (!fs.existsSync(filePath)) {
    return (
      <main className="max-w-4xl mx-auto py-16 px-6 text-center">
        <h1 className="text-3xl font-serif text-temple-ink mb-4">{title}</h1>
        <p className="text-quiet-ink">
          The content for this topic ({topic_id}) is currently being generated by the AI research pipeline. Please check back later.
        </p>
      </main>
    );
  }

  const data = JSON.parse(fs.readFileSync(filePath, 'utf8'));

  return (
    <main className="max-w-5xl mx-auto py-12 px-6">
      <header className="mb-12 border-b border-carved-line pb-8">
        <div className="flex items-center gap-4 mb-4">
          <span className="text-sm font-mono text-aged-brass font-semibold tracking-wider">
            {topic_id}
          </span>
          <h1 className="text-4xl font-serif text-temple-ink">{title}</h1>
        </div>
      </header>

      <div className="prose prose-lg prose-stone max-w-none mb-16">
        {data.overview.split('\n').map((paragraph: string, i: number) => (
          <p key={i} className="text-[#2C3E50] leading-relaxed">
            {paragraph}
          </p>
        ))}
      </div>

      {data.primary_sources && data.primary_sources.length > 0 && (
        <section className="mb-16">
          <h2 className="text-2xl font-serif text-temple-ink mb-6">Primary Sources</h2>
          <div className="space-y-6">
            {data.primary_sources.map((source: any, i: number) => (
              <ScriptureReader 
                key={i}
                title={source.title}
                author={source.author}
                originalText={source.original_text}
                transliteration={source.transliteration}
                translation={source.translation}
                sourceNotes={source.notes}
              />
            ))}
          </div>
        </section>
      )}

      {data.misconceptions && data.misconceptions.length > 0 && (
        <section className="bg-soft-stone/20 p-8 rounded-sm border border-carved-line/30">
          <h2 className="text-xl font-serif text-temple-ink mb-4">Common Misconceptions</h2>
          <ul className="space-y-4">
            {data.misconceptions.map((misc: any, i: number) => (
              <li key={i} className="flex gap-4">
                <span className="text-aged-brass font-bold">✗</span>
                <div>
                  <p className="font-medium text-[#1A252C]">{misc.myth}</p>
                  <p className="text-sm text-quiet-ink mt-1">{misc.reality}</p>
                </div>
              </li>
            ))}
          </ul>
        </section>
      )}
    </main>
  );
}
